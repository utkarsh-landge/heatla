"""Member 1 - write every result table as markdown, straight from the CSV outputs.

Sections I-K cover the follow-up runs (level-only target, and the ablation without the
asthma and cardiovascular inputs); they are skipped if those run folders do not exist.

Nothing is typed by hand: reports/member1_tables.md is regenerated from
results/member1/** so the report tables cannot drift from the metric files.

Run:  .venv/bin/python scripts/build_member1_tables.py
"""
from __future__ import annotations

import json
import pathlib

import pandas as pd

BASE = pathlib.Path("results/member1")
OUT = pathlib.Path("reports/member1_tables.md")
VARIANTS = [("ces40_original", BASE, "CES 4.0 original (uncorrected, superseded)"),
            ("ces40_fixed", BASE / "ces40_fixed", "CES 4.0 corrected"),
            ("ces30", BASE / "ces30", "CES 3.0")]
SHORT = {"ces40_original": "4.0 orig", "ces40_fixed": "4.0 fixed", "ces30": "3.0"}
MODELS = [("poisson", "Poisson"), ("random_forest", "Random forest"),
          ("gradient_boosting", "Gradient boosting")]
SCOPES = ["pooled (levels 1-4)", "level 1", "level 2", "level 3", "level 4"]
EVALS = [("la_holdout", "LA holdout (train: rest of California; test: LA County)"),
         ("spatial_cv", "Statewide spatial cross-validation (10 folds)")]


def f3(v):
    return "—" if pd.isna(v) else f"{v:.3f}".replace("-", "−")


def f2(v):
    return "—" if pd.isna(v) else f"{v:.2f}".replace("-", "−")


def md(rows: list[dict]) -> str:
    cols = list(rows[0])
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    out += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    L: list[str] = ["# Member 1 — full result tables (generated)", "",
                    "Generated by `scripts/build_member1_tables.py` from `results/member1/`. "
                    "Do not edit by hand.", ""]
    metrics = {k: pd.read_csv(d / "metrics_by_level.csv") for k, d, _ in VARIANTS}
    ces = {k: pd.read_csv(d / "baseline_ces_matched.csv") for k, d, _ in VARIANTS}

    # ---- A. input audit
    L += ["## A. Input audit", "", "### A1. Sentinel and blank values in the tract files", "",
          md(pd.read_csv(BASE / "input_checks/sentinel_audit_tracts.csv").to_dict("records")), "",
          "### A2. ZIP-level features: original 4.0, corrected 4.0 and 3.0", "",
          md(pd.read_csv(BASE / "input_checks/feature_comparison_zip_level.csv").to_dict("records")),
          "", "### A3. Table checks", "",
          md(pd.read_csv(BASE / "input_checks/table_checks.csv").to_dict("records")), ""]

    # ---- B. sample counts per variant
    L += ["## B. Sample counts", ""]
    for k, d, name in VARIANTS:
        L += [f"### {name}", "", md(pd.read_csv(d / "sample_counts.csv").to_dict("records")), ""]
    L += ["### Fold counts (identical across variants except the missing-input column)", ""]
    for k, d, name in VARIANTS:
        fc = pd.read_csv(d / "fold_counts_statewide.csv").drop(
            columns=["centroid_lat", "centroid_lon", "rows_per_level"])
        L += [f"**{name}**", "", md(fc.to_dict("records")), ""]

    # ---- C. three-way comparison, all-level model
    L += ["## C. All-level model: three input variants side by side", ""]
    for ev, evname in EVALS:
        rows = []
        for mk, mname in MODELS:
            for sc in SCOPES:
                r = {"Model": mname, "Scope": sc}
                for col, lab, fmt in (("r2", "R²", f3), ("spearman", "ρ", f3),
                                      ("top10_recall", "Top-10%", f2),
                                      ("top20_recall", "Top-20%", f2)):
                    for k, _, _ in VARIANTS:
                        m = metrics[k]
                        v = m[(m.evaluation == ev) & (m.config == "all_level")
                              & (m.model == mk) & (m.scope == sc)].iloc[0]
                        r[f"{lab} {SHORT[k]}"] = fmt(v[col])
                r["n"] = int(v["n"])
                rows.append(r)
        L += [f"### {evname}", "", md(rows), ""]

    # ---- D. all-level vs level-specific, per variant
    L += ["## D. All-level vs level-specific models", ""]
    for k, d, name in VARIANTS:
        m = metrics[k]
        for ev, evname in EVALS:
            rows = []
            for mk, mname in MODELS:
                for sc in SCOPES[1:] + SCOPES[:1]:
                    a = m[(m.evaluation == ev) & (m.model == mk) & (m.scope == sc)
                          & (m.config == "all_level")].iloc[0]
                    b = m[(m.evaluation == ev) & (m.model == mk) & (m.scope == sc)
                          & (m.config == "level_specific")].iloc[0]
                    rows.append({"Model": mname, "Scope": sc, "n": int(a.n),
                                 "R² all": f3(a.r2), "R² specific": f3(b.r2),
                                 "ρ all": f3(a.spearman), "ρ specific": f3(b.spearman),
                                 "Top-10% all": f2(a.top10_recall),
                                 "Top-10% specific": f2(b.top10_recall),
                                 "Top-20% all": f2(a.top20_recall),
                                 "Top-20% specific": f2(b.top20_recall)})
            L += [f"### {name} — {evname}", "", md(rows), ""]

    # ---- E. CES baseline, matched samples
    L += ["## E. CalEnviroScreen percentile baseline on matched samples", "",
          "Each block uses only ZIPs with a percentile in that variant, at one heat level. "
          "Rank metrics only.", ""]
    names = dict(MODELS)
    for k, d, name in VARIANTS:
        c = ces[k]
        for ev, evname in EVALS:
            rows = []
            for sc in SCOPES[1:]:
                s = c[(c.evaluation == ev) & (c.scope == sc) & c.config.isin(["index", "all_level"])]
                for r in s.itertuples():
                    rows.append({"Heat level": sc, "ZIPs (all)": r.n_all,
                                 "ZIPs matched": r.n_matched, "Dropped": r.n_dropped_no_ces,
                                 "Predictor": names.get(r.predictor, r.predictor),
                                 "ρ": f3(r.spearman), "Top-10%": f2(r.top10_recall),
                                 "Top-20%": f2(r.top20_recall)})
            L += [f"### {name} — {evname}", "", md(rows), ""]

    # ---- F. same ZIPs, complete inputs
    cc = pd.read_csv(BASE / "comparison/metrics_common_complete.csv")
    cnt = pd.read_csv(BASE / "comparison/sample_counts_by_variant.csv")
    L += ["## F. Same ZIPs with complete inputs in both corrected 4.0 and 3.0", "",
          md(cnt.to_dict("records")), ""]
    pn = {**names, "ces_percentile": "CES percentile (that version)"}
    for ev, evname in EVALS:
        rows = []
        for pk in ["poisson", "random_forest", "gradient_boosting", "ces_percentile"]:
            for sc in SCOPES:
                r = {"Predictor": pn[pk], "Scope": sc}
                for col, lab, fmt in (("r2", "R²", f3), ("spearman", "ρ", f3),
                                      ("top10_recall", "Top-10%", f2)):
                    for k, _, _ in VARIANTS:
                        s = cc[(cc.variant == k) & (cc.evaluation == ev) & (cc.predictor == pk)
                               & (cc.scope == sc) & cc.config.isin(["all_level", "index"])]
                        r[f"{lab} {SHORT[k]}"] = fmt(s.iloc[0][col]) if len(s) else "—"
                r["n"] = int(s.iloc[0]["n"]) if len(s) else "—"
                rows.append(r)
        L += [f"### {evname}", "", md(rows), ""]

    # ---- G. errors by level (Poisson, LA holdout)
    L += ["## G. Poisson error by heat level, LA holdout (prediction − UCLA label, per 10,000)", ""]
    for k, d, name in VARIANTS:
        p = pd.read_csv(d / "predictions_la_holdout.csv", dtype={"zip": str})
        rows = []
        for cfg in ("all_level", "level_specific"):
            for lv, g in p.groupby("chs_level"):
                e = g[f"error_poisson_{cfg}"]
                rows.append({"Config": cfg, "Heat level": lv,
                             "Label mean": f2(g.ucla_label.mean()), "Label SD": f2(g.ucla_label.std()),
                             "Prediction mean": f2(g[f"pred_poisson_{cfg}"].mean()),
                             "Prediction SD": f2(g[f"pred_poisson_{cfg}"].std()),
                             "Mean error": f"{e.mean():+.2f}".replace("-", "−"),
                             "Mean abs error": f2(e.abs().mean()),
                             "Overpredicted": f"{(e > 0).mean():.0%}"})
        L += [f"### {name}", "", md(rows), ""]
        g = p[p.chs_level == 4].copy()
        g["prefix"] = g["zip"].str.zfill(5).str[:3]
        t = g.groupby("prefix").agg(zips=("zip", "size"), label=("ucla_label", "mean"),
                                    err_all=("error_poisson_all_level", "mean"),
                                    err_spec=("error_poisson_level_specific", "mean"))
        t = t[t.zips >= 10].sort_values("err_all", ascending=False)
        rows = [{"ZIP prefix": i, "ZIPs": int(r.zips), "Mean label": f2(r.label),
                 "Mean error, all-level": f"{r.err_all:+.2f}".replace("-", "−"),
                 "Mean error, level-specific": f"{r.err_spec:+.2f}".replace("-", "−")}
                for i, r in t.iterrows()]
        L += [f"**Level-4 error by ZIP prefix — {name}**", "", md(rows), ""]

    # ---- H. confidence intervals for headline numbers
    L += ["## H. Bootstrap 95% confidence intervals (1,000 resamples)", ""]
    rows = []
    for k, d, name in VARIANTS:
        J = json.loads((d / "metrics_member1.json").read_text())["metrics"]
        for r in J:
            if r["model"] == "trainmean" or r["scope"] not in ("level 4", "pooled (levels 1-4)"):
                continue
            rows.append({"Variant": name, "Evaluation": r["evaluation"], "Config": r["config"],
                         "Model": names[r["model"]], "Scope": r["scope"], "n": r["n"],
                         "R²": f3(r["r2"]),
                         "R² CI": f"{f3(r['r2_ci'][0])} to {f3(r['r2_ci'][1])}",
                         "ρ": f3(r["spearman"]),
                         "ρ CI": f"{f3(r['spearman_ci'][0])} to {f3(r['spearman_ci'][1])}",
                         "Top-10% k": r["top10_k"]})
    L += [md(rows), ""]

    # ---- I. level-only target (extreme heat specifically)
    FX = BASE / "ces40_fixed"
    LO, NE, LONE = (BASE / "ces40_fixed_level_only", BASE / "ces40_fixed_no_ed",
                    BASE / "ces40_fixed_level_only_no_ed")
    if LO.exists():
        mc, ml = pd.read_csv(FX / "metrics_by_level.csv"), pd.read_csv(LO / "metrics_by_level.csv")

        def pick(m, ev, cfg, mk, sc):
            return m[(m.evaluation == ev) & (m.config == cfg) & (m.model == mk) & (m.scope == sc)].iloc[0]
        L += ["## I. Level-only target: the excess on each level's days alone", "",
              "Corrected CES 4.0 inputs. Cumulative = the label as published (all days at or "
              "below the level). Level-only = label(k) minus label(k-1); level 1 is unchanged. "
              "Same ZIPs, folds, inputs and models in both.", ""]
        for ev, evname in EVALS:
            rows = []
            for mk, mname in MODELS:
                for sc in SCOPES[1:] + SCOPES[:1]:
                    c, a, b = (pick(mc, ev, "all_level", mk, sc), pick(ml, ev, "all_level", mk, sc),
                               pick(ml, ev, "level_specific", mk, sc))
                    rows.append({"Model": mname, "Scope": sc, "n": int(c.n),
                                 "R² cumulative": f3(c.r2), "R² level-only": f3(a.r2),
                                 "R² level-only, level-specific model": f3(b.r2),
                                 "ρ cumulative": f3(c.spearman), "ρ level-only": f3(a.spearman),
                                 "ρ level-only, level-specific model": f3(b.spearman),
                                 "Top-10% cumulative": f2(c.top10_recall),
                                 "Top-10% level-only": f2(a.top10_recall),
                                 "Top-10% level-only, level-specific model": f2(b.top10_recall)})
            L += [f"### {evname}", "", md(rows), ""]
        cl = pd.read_csv(LO / "baseline_ces_matched.csv")
        for ev, evname in EVALS:
            rows = []
            for sc in SCOPES[1:]:
                sub = cl[(cl.evaluation == ev) & (cl.scope == sc)]
                for r in sub.itertuples():
                    rows.append({"Heat level": sc, "ZIPs matched": r.n_matched,
                                 "Predictor": names.get(r.predictor, r.predictor),
                                 "Config": r.config, "ρ": f3(r.spearman),
                                 "Top-10%": f2(r.top10_recall), "Top-20%": f2(r.top20_recall)})
            L += [f"### CES baseline on the level-only target — {evname}", "", md(rows), ""]
        pl = pd.read_csv(LO / "predictions_la_holdout.csv", dtype={"zip": str})
        rows = []
        for cfg in ("all_level", "level_specific"):
            for lv, g in pl.groupby("chs_level"):
                e = g[f"error_poisson_{cfg}"]
                rows.append({"Config": cfg, "Heat level": lv, "Label mean": f2(g.ucla_label.mean()),
                             "Label SD": f2(g.ucla_label.std()),
                             "Prediction mean": f2(g[f"pred_poisson_{cfg}"].mean()),
                             "Prediction SD": f2(g[f"pred_poisson_{cfg}"].std()),
                             "Mean error": f"{e.mean():+.2f}".replace("-", "−"),
                             "Mean abs error": f2(e.abs().mean()),
                             "Overpredicted": f"{(e > 0).mean():.0%}"})
        L += ["### Poisson error on the level-only target, LA holdout", "", md(rows), ""]

    # ---- J. ablation: without the asthma and cardiovascular ED-rate inputs
    if NE.exists():
        L += ["## J. Without the asthma and cardiovascular inputs", "",
              "Corrected CES 4.0 inputs. 'With' uses all 12 inputs; 'without' leaves out "
              "asthma_ed_per10k and cardiovascular_ed_per10k (10 inputs). Same ZIPs and folds.", ""]
        pairs = [("cumulative target", FX, NE)]
        if LONE.exists():
            pairs.append(("level-only target", LO, LONE))
        for tname, with_dir, wo_dir in pairs:
            mw, mo = pd.read_csv(with_dir / "metrics_by_level.csv"), pd.read_csv(wo_dir / "metrics_by_level.csv")
            for ev, evname in EVALS:
                rows = []
                for mk, mname in MODELS:
                    for cfg in ("all_level", "level_specific"):
                        for sc in SCOPES[1:] + SCOPES[:1]:
                            a = mw[(mw.evaluation == ev) & (mw.config == cfg) & (mw.model == mk) & (mw.scope == sc)].iloc[0]
                            b = mo[(mo.evaluation == ev) & (mo.config == cfg) & (mo.model == mk) & (mo.scope == sc)].iloc[0]
                            rows.append({"Model": mname, "Config": cfg, "Scope": sc, "n": int(a.n),
                                         "R² with": f3(a.r2), "R² without": f3(b.r2),
                                         "ρ with": f3(a.spearman), "ρ without": f3(b.spearman),
                                         "Top-10% with": f2(a.top10_recall),
                                         "Top-10% without": f2(b.top10_recall),
                                         "Top-20% with": f2(a.top20_recall),
                                         "Top-20% without": f2(b.top20_recall)})
                L += [f"### {tname} — {evname}", "", md(rows), ""]

    # ---- K. confidence intervals for the follow-up runs
    extra = [(d, n) for d, n in ((LO, "Level-only target"), (NE, "Cumulative, no ED-rate inputs"),
                                 (LONE, "Level-only, no ED-rate inputs")) if d.exists()]
    if extra:
        rows = []
        for d, name in extra:
            for r in json.loads((d / "metrics_member1.json").read_text())["metrics"]:
                if r["model"] == "trainmean" or r["scope"] != "level 4":
                    continue
                rows.append({"Variant": name, "Evaluation": r["evaluation"], "Config": r["config"],
                             "Model": names[r["model"]], "n": r["n"], "R²": f3(r["r2"]),
                             "R² CI": f"{f3(r['r2_ci'][0])} to {f3(r['r2_ci'][1])}",
                             "ρ": f3(r["spearman"]),
                             "ρ CI": f"{f3(r['spearman_ci'][0])} to {f3(r['spearman_ci'][1])}"})
        L += ["## K. Level 4: bootstrap 95% confidence intervals, follow-up runs", "", md(rows), ""]

    OUT.write_text("\n".join(L))
    print("wrote", OUT, f"({len(L)} lines)")


if __name__ == "__main__":
    main()
